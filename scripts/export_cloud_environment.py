"""Export the resolved Linux Pixi environment for Streamlit Community Cloud."""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any
from urllib.parse import urlparse

import yaml

ROOT = Path(__file__).resolve().parents[1]


def render_environment(lock: dict[str, Any]) -> str:
    """Export supported lock-v6 package records with exact resolved versions.

    Args:
        lock: Parsed Pixi lock file with the default Linux environment.

    Returns:
        Conda environment YAML, including pip pins and the local editable package.

    Raises:
        ValueError: If the lock format or a package source is unsupported.
    """
    if lock.get("version") != 6:
        message = "Expected Pixi lock format 6; review the exporter before upgrading."
        raise ValueError(message)
    environment = lock["environments"]["default"]
    records = {
        (kind, p[kind]): p
        for p in lock["packages"]
        for kind in ("conda", "pypi")
        if kind in p
    }
    conda, pip = [], []
    for reference in environment["packages"]["linux-64"]:
        if len(reference) != 1 or next(iter(reference)) not in {"conda", "pypi"}:
            message = "Unsupported Linux package reference."
            raise ValueError(message)
        kind, source = next(iter(reference.items()))
        package = records[kind, source]
        if kind == "conda":
            conda.append(_conda_pin(source))
        elif source == "./" and package["name"] == "household-forecast":
            pip.append("-e .")
        elif urlparse(source).hostname == "files.pythonhosted.org":
            pip.append(f"{package['name']}=={package['version']}")
        else:
            message = f"Unsupported pip source for {package.get('name', 'package')}."
            raise ValueError(message)
    result = {
        "name": "household-forecast",
        "channels": [channel["url"] for channel in environment["channels"]],
        "dependencies": [*sorted(conda), {"pip": sorted(pip)}],
    }
    return (
        "# Generated by pixi run export-cloud; edit pixi.lock through Pixi.\n"
        + yaml.safe_dump(result, sort_keys=False)
    )


def _conda_pin(source: str) -> str:
    """Decode the version and build from a resolved conda package filename."""
    url = urlparse(source)
    if url.scheme != "https" or url.hostname != "conda.anaconda.org":
        message = "Expected a public conda package URL."
        raise ValueError(message)
    filename = Path(url.path).name
    for extension in (".conda", ".tar.bz2"):
        if filename.endswith(extension):
            name, version, build = filename.removesuffix(extension).rsplit("-", 2)
            return f"{name}={version}={build}"
    message = "Unsupported conda package archive."
    raise ValueError(message)


def main() -> None:
    """Write the generated environment or fail if the checked-in copy is stale."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render_environment(yaml.safe_load((ROOT / "pixi.lock").read_text()))
    target = ROOT / "environment.yml"
    if args.check:
        if not target.exists() or target.read_text() != content:
            parser.exit(1, "environment.yml is stale; run pixi run export-cloud.\n")
    else:
        target.write_text(content)


if __name__ == "__main__":
    main()
